-- receitas, despesas, saldo mensal e taxas por data
-- Execute SOMENTE em um banco que ainda nao tenha estas quatro tabelas.
-- As tabelas anteriores (USUARIO, TAXA_EXERCICIO etc.) permanecem intactas.

CREATE TABLE RECEITA (
    ID_RECEITA INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_USUARIO INTEGER NOT NULL,
    DESCRICAO VARCHAR(100) NOT NULL,
    VALOR DECIMAL(12,2) NOT NULL CHECK (VALOR > 0),
    DATA_RECEITA DATE NOT NULL,
    CONSTRAINT FK_RECEITA_USUARIO FOREIGN KEY (ID_USUARIO)
        REFERENCES USUARIO (ID_USUARIO)
);

CREATE TABLE DESPESA (
    ID_DESPESA INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_USUARIO INTEGER NOT NULL,
    DESCRICAO VARCHAR(100) NOT NULL,
    VALOR DECIMAL(12,2) NOT NULL CHECK (VALOR > 0),
    CLASSIFICACAO VARCHAR(10) NOT NULL
        CHECK (CLASSIFICACAO IN ('Fixa', 'Variavel')),
    DATA_DESPESA DATE NOT NULL,
    CONSTRAINT FK_DESPESA_USUARIO FOREIGN KEY (ID_USUARIO)
        REFERENCES USUARIO (ID_USUARIO)
);

CREATE TABLE SALDO_MENSAL (
    ID_USUARIO INTEGER NOT NULL,
    ANO INTEGER NOT NULL,
    MES INTEGER NOT NULL CHECK (MES BETWEEN 1 AND 12),
    TOTAL_RECEITAS DECIMAL(12,2) NOT NULL,
    TOTAL_DESPESAS DECIMAL(12,2) NOT NULL,
    SALDO DECIMAL(12,2) NOT NULL,
    CONSTRAINT PK_SALDO_MENSAL PRIMARY KEY (ID_USUARIO, ANO, MES),
    CONSTRAINT FK_SALDO_MENSAL_USUARIO FOREIGN KEY (ID_USUARIO)
        REFERENCES USUARIO (ID_USUARIO)
);

CREATE TABLE TAXA_JUROS (
    ID_TAXA INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_USUARIO INTEGER NOT NULL,
    PERCENTUAL DECIMAL(9,4) NOT NULL CHECK (PERCENTUAL >= 0),
    DATA_REFERENCIA DATE NOT NULL,
    CONSTRAINT UQ_TAXA_DATA UNIQUE (DATA_REFERENCIA),
    CONSTRAINT FK_TAXA_JUROS_USUARIO FOREIGN KEY (ID_USUARIO)
        REFERENCES USUARIO (ID_USUARIO)
);

COMMIT;
